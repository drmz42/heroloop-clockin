import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const read=p=>readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const compose=read('selfhosted/compose.hackathon.yml');
assert.match(compose,/127\.0\.0\.1:25432:5432/);
assert.match(compose,/127\.0\.0\.1:29999:9999/);
assert.match(compose,/127\.0\.0\.1:28081:8080/);
assert.doesNotMatch(compose,/18081|19999|15432|external: true/);
assert.match(compose,/HERO_DISTRIBUTION_ENABLED: "false"/);
assert.match(compose,/TESTER_CONTROLS_ENABLED: "false"/);
const install=read('ops/install-selfhosted-hackathon-runtime.sh');
assert.match(install,/project=heroloop-selfhosted-hackathon/);
assert.doesNotMatch(install,/compose\.staging\.yml|pg_dump|DROP DATABASE|down --volumes|selfhosted-staging\.env/);
assert.match(install,/REVOKE CONNECT ON DATABASE seeker_skr FROM PUBLIC/);
assert.match(install,/selfhosted\/seeker\/ledger\.sql/);
const secret=read('ops/init-selfhosted-hackathon-secrets.mjs');
assert.match(secret,/O_EXCL/); assert.match(secret,/O_NOFOLLOW/);
assert.doesNotMatch(secret,/readFileSync\([^)]*staging\.env|copyFile/);
const ordinary=read('selfhosted/compose.staging.yml');
assert.doesNotMatch(ordinary,/staging2\.heroloop\.xyz/);
const worker=read('selfhosted/worker/main.ts');
assert.match(worker,/set_config\('heroloop\.hero_distribution_enabled'/);
assert.match(worker,/run_distribution_tick/);
const tick=read('selfhosted/postgres/migrations/20261001180000_worker_optional_hero_distribution.sql');
assert.match(tick,/settle_periodic_progression/);
assert.match(tick,/THEN 0 ELSE 20000/);
assert.match(tick,/v_tick_amount numeric := v_daily_pool/);
const storage=read('src/game/editionStorage.ts');
assert.match(storage,/\['staging2', 'seeker'\]/);
assert.match(storage,/heroloop-seeker:v1:/);
for (const mode of ['staging', 'production', 'staging2', 'seeker']) {
  const compiled=stripTypeScriptTypes(storage).replaceAll('import.meta.env',JSON.stringify({MODE:mode}));
  const {editionStorageKey}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
  const oldKey='afk-heroes-save-v7';
  const store=new Map([[oldKey,'ordinary-save']]);
  const key=editionStorageKey(oldKey);
  if (['staging2','seeker'].includes(mode)) {
    assert.equal(store.get(key),undefined,'hackathon consumed the former shared-game save');
    store.set(key,'hackathon-save');
    store.delete(key);
    assert.equal(store.get(oldKey),'ordinary-save','hackathon reset removed the former save');
  } else assert.equal(store.get(key),'ordinary-save','ordinary build changed its save namespace');
}
for(const p of ['src/game/state.ts','src/game/solanaWalletSession.ts','src/game/solanaWalletBinding.ts','src/screens/MainScreen.tsx']) assert.match(read(p),/editionStorageKey\(/);
assert.match(read('src/game/backend.ts'),/storageKey: editionStorageKey\('auth'\)/);
const deploy=read('ops/deploy-staging2-release.sh');
assert.match(deploy,/backend_contour=hackathon/);
assert.match(deploy,/route_changed=true/);
assert.match(deploy,/nginx-previous\.conf/);
assert.ok(deploy.indexOf('trap restore_release ERR')<deploy.indexOf('route_changed=true'));
assert.match(read('ops/rollback-staging2-release.sh'),/backend_contour=hackathon/);
console.log('Hackathon isolation contract PASS.');
